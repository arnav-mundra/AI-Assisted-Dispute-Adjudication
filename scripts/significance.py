"""Paired significance tests on decision correctness, from saved runs only.

    python scripts/significance.py      # writes results/significance.md

Each configuration is scored on the same 26 cases (10 pilot + 16 counterfactual), so
two configurations are compared case by case with an exact McNemar test (a two-sided
binomial test on the discordant cases). Holm's method corrects for multiple comparisons
within each family of tests. Where a configuration was repeated, its first (grid) run is
used so every configuration contributes one ruling per case. Held-out runs are never read.
"""

import sys
from itertools import combinations
from pathlib import Path
from typing import Dict, List, Sequence, Tuple

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from scipy.stats import binomtest  # noqa: E402

from src.config.paths import RESULTS_DIR  # noqa: E402
from src.evaluation.datasets import load_dataset  # noqa: E402
from src.evaluation.experiment import list_runs  # noqa: E402
from src.evaluation.metrics import score_run  # noqa: E402

DATASETS = ("pilot", "counterfactual")
MODELS = (("openai/gpt-oss-120b", "120b"), ("qwen/qwen3.8-27b", "qwen"), ("openai/gpt-oss-20b", "20b"))
STYLES = ("zero_shot", "facts", "cot")
RULES = "rules engine"


def mcnemar_exact(a: Sequence[bool], b: Sequence[bool]) -> Tuple[int, int, float]:
    """Cases only A got right, cases only B got right, and the exact two-sided p-value."""
    only_a = sum(x and not y for x, y in zip(a, b))
    only_b = sum(y and not x for x, y in zip(a, b))
    p = binomtest(only_a, only_a + only_b, 0.5).pvalue if only_a + only_b else 1.0
    return only_a, only_b, p


def holm(pvalues: List[float]) -> List[float]:
    """Holm-adjusted p-values, in the input order."""
    order = sorted(range(len(pvalues)), key=lambda i: pvalues[i])
    adjusted, running = [0.0] * len(pvalues), 0.0
    for rank, i in enumerate(order):
        running = max(running, min(1.0, (len(pvalues) - rank) * pvalues[i]))
        adjusted[i] = running
    return adjusted


def correctness() -> Dict[str, List[bool]]:
    """Per configuration label: correct/incorrect for each case, pilot then counterfactual, in label order."""
    table: Dict[str, List[bool]] = {}
    for dataset in DATASETS:
        _, labels = load_dataset(dataset)
        seen = set()
        for run in sorted(list_runs(dataset), key=lambda r: r.get("created_at", "")):
            config = run.get("config", {})
            if config.get("guard") or config.get("min_confidence"):
                continue
            if config.get("engine") == "rules":
                name = RULES
            else:
                short = dict(MODELS).get(config.get("model"))
                if short is None:
                    continue
                name = f"{short}, {config.get('prompt_style')}"
            if name in seen:
                continue  # a repeat: keep the first run so each case counts once
            seen.add(name)
            rows = {r["case_id"]: r["correct"] for r in score_run(run["predictions"], labels)["per_case"]}
            table.setdefault(name, []).extend(rows.get(l["case_id"], False) for l in labels)
    return table


def family(table, pairs, title, note):
    rows = [(a, b) + mcnemar_exact(table[a], table[b]) for a, b in pairs]
    adjusted = holm([r[4] for r in rows])
    lines = [f"## {title}", "", note, "",
             "| A | B | Acc. A | Acc. B | Only A right | Only B right | p (exact) | p (Holm) |",
             "|---|---|---|---|---|---|---|---|"]
    for (a, b, only_a, only_b, p), p_adj in zip(rows, adjusted):
        acc_a = sum(table[a]) / len(table[a])
        acc_b = sum(table[b]) / len(table[b])
        lines.append(f"| {a} | {b} | {acc_a:.0%} | {acc_b:.0%} | {only_a} | {only_b} | {p:.3f} | {p_adj:.3f} |")
    lines.append("")
    return lines, min(adjusted) if adjusted else 1.0


def main():
    table = correctness()
    n = {len(v) for v in table.values()}
    assert n == {26}, f"expected 26 scored cases per configuration, got {n}"
    llm = [f"{short}, {style}" for _, short in MODELS for style in STYLES]
    missing = [c for c in llm + [RULES] if c not in table]
    assert not missing, f"missing configurations: {missing}"

    out = ["# Paired significance tests", "",
           "Generated by `scripts/significance.py` from `results/runs/`. Exact McNemar tests on per-case "
           "decision correctness over the 26 pilot and counterfactual cases; p-values are Holm-adjusted "
           "within each table. Repeated configurations use their first run.", ""]
    families = [
        ("Each LLM configuration vs the rules engine", [(c, RULES) for c in llm],
         "The rules engine was written with the pilot cases visible, so this comparison favours it."),
        ("Prompt styles within each model", [(f"{s}, {a}", f"{s}, {b}") for _, s in MODELS
                                             for a, b in combinations(STYLES, 2)], ""),
        ("Models within each prompt style", [(f"{a}, {st}", f"{b}, {st}") for st in STYLES
                                             for (_, a), (_, b) in combinations(MODELS, 2)], ""),
    ]
    summary = []
    for title, pairs, note in families:
        lines, best = family(table, pairs, title, note)
        out += lines
        summary.append(f"- {title}: smallest Holm-adjusted p = {best:.3f}")
    out[4:4] = ["Summary:", ""] + summary + [""]  # after the intro, before the first table
    path = RESULTS_DIR / "significance.md"
    path.write_text("\n".join(out), encoding="utf-8")
    print("\n".join(summary))
    print("wrote", path)


if __name__ == "__main__":
    assert holm([0.01, 0.04, 0.03]) == [0.03, 0.06, 0.06]
    assert mcnemar_exact([True] * 6, [False] * 6)[2] < 0.05
    main()
