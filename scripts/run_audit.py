"""Two checks over saved LLM runs that reviewers asked about, written to results/run_audit.md.

    python scripts/run_audit.py

1. Repair rounds: how often the first answer failed grounding/schema checks and was repaired.
2. Cross-family context: how often one-hop expansion put a clause from the other dispute family
   (DG for a COD case, COD for a DG case) into the prompt, and how often a ruling cited one.
"""

import sys
from collections import Counter
from pathlib import Path
from typing import Any, Dict, List, Sequence

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from results_tables import FULL_CONTEXT_K, usable_runs  # noqa: E402
from src.config.paths import RESULTS_DIR  # noqa: E402
from src.evaluation.datasets import load_cases  # noqa: E402
from src.evaluation.experiment import list_runs  # noqa: E402

OTHER_FAMILY = {"DAMAGED_GOODS": "SLA-COD-", "COD_MISMATCH": "SLA-DG-"}


def repaired(prediction: Dict[str, Any]) -> bool:
    return any("repaired after" in w for w in prediction.get("warnings") or [])


def cross_family(prediction: Dict[str, Any], dispute_type: str) -> Dict[str, bool]:
    prefix = OTHER_FAMILY[dispute_type]
    cited = [prediction.get("primary_clause_id") or ""] + list(prediction.get("supporting_clause_ids") or [])
    return {"in_prompt": any(c.startswith(prefix) for c in prediction.get("retrieved_clause_ids") or []),
            "cited": any(c.startswith(prefix) for c in cited)}


def audit(runs: Sequence[Dict[str, Any]]) -> Dict[str, Counter]:
    types: Dict[str, Dict[str, str]] = {}
    out = {"rulings": Counter(), "repaired": Counter(), "in_prompt": Counter(), "cited": Counter()}
    for run in runs:
        dataset = run["config"]["dataset"]
        if dataset not in types:
            types[dataset] = {c["case_id"]: c["dispute_type"] for c in load_cases(dataset)}
        for p in run["predictions"]:
            flags = cross_family(p, types[dataset][p["case_id"]])
            out["rulings"][dataset] += 1
            out["repaired"][dataset] += repaired(p)
            out["in_prompt"][dataset] += flags["in_prompt"]
            out["cited"][dataset] += flags["cited"]
    return out


def render(counts: Dict[str, Counter]) -> str:
    datasets = sorted(counts["rulings"]) + ["all"]
    for key in counts:
        counts[key]["all"] = sum(v for k, v in counts[key].items() if k != "all")
    lines = ["# Run audit: repair rounds and cross-family context", "",
             "Generated by `scripts/run_audit.py` from the runs in `results/icaaic_summary.md` "
             "(unguarded LLM runs with retrieval; full-context runs excluded). Do not edit by hand.", "",
             "| Dataset | LLM rulings | Repaired once | Wrong-family clause in prompt | Wrong-family clause cited |",
             "|---|---|---|---|---|"]
    for d in datasets:
        n = counts["rulings"][d]
        cells = [f"{counts[k][d]} ({counts[k][d] / n:.0%})" for k in ("repaired", "in_prompt", "cited")]
        lines.append(f"| {d} | {n} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def main() -> None:
    # full-context runs put every clause in the prompt by design, so they say nothing about retrieval
    runs = [r for r in usable_runs(list_runs()) if r["config"]["engine"] == "llm"
            and int(r["config"].get("top_k") or 0) < FULL_CONTEXT_K]
    (RESULTS_DIR / "run_audit.md").write_text(render(audit(runs)), encoding="utf-8")
    print((RESULTS_DIR / "run_audit.md").read_text(encoding="utf-8"))


if __name__ == "__main__":
    assert cross_family({"retrieved_clause_ids": ["SLA-COD-03"], "primary_clause_id": "SLA-DG-06"},
                        "DAMAGED_GOODS") == {"in_prompt": True, "cited": False}
    assert repaired({"warnings": ["repaired after: unknown clause"]}) and not repaired({"warnings": []})
    main()
